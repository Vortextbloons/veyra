// Generates src/modules/chat/ui/generated.ts (system prompt) and
// generated-schema.ts (parser schema) from the interactive answer component
// library. Run with `npm run prompt:ui` after changing the library, the prompt
// rules or the examples.
//
// The library is React/TSX, so it is bundled with esbuild into a temporary ESM
// module (all packages stay external) and imported once.

import { build } from "esbuild";
import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

const root = path.resolve(import.meta.dirname, "..");
const srcDir = path.join(root, "src");
const uiDir = path.join(srcDir, "modules", "chat", "ui");
const cacheDir = path.join(root, "node_modules", ".cache", "veyra");
const outfile = path.join(cacheDir, "interactive-prompt.mjs");
const promptTarget = path.join(uiDir, "generated.ts");
const schemaTarget = path.join(uiDir, "generated-schema.ts");

/** Resolves the app's `@/…` alias without touching scoped packages like `@openuidev/…`. */
const aliasPlugin = {
  name: "veyra-alias",
  setup(build) {
    build.onResolve({ filter: /^@\// }, (args) =>
      build.resolve("./" + args.path.slice(2), { resolveDir: srcDir, kind: args.kind }),
    );
    // Stylesheets are irrelevant to a prompt and cannot be imported by Node.
    build.onResolve({ filter: /\.css$/ }, (args) => ({ path: args.path, namespace: "empty-css" }));
    build.onLoad({ filter: /.*/, namespace: "empty-css" }, () => ({ contents: "", loader: "js" }));
  },
};

await mkdir(cacheDir, { recursive: true });
await build({
  entryPoints: [path.join(uiDir, "prompt-entry.ts")],
  outfile,
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node20",
  jsx: "automatic",
  packages: "external",
  plugins: [aliasPlugin],
  logLevel: "warning",
});

const module = await import(pathToFileURL(outfile).href + `?v=${Date.now()}`);
const { prompt, schema, root: rootComponent } = module.buildInteractiveAnswerArtifacts();

const promptContents = [
  "// Generated by scripts/generate-interactive-prompt.mjs — do not edit by hand.",
  "// Run `npm run prompt:ui` after changing the component library, prompt rules or examples.",
  "// The prompt is a plain string, so the app never loads the renderer to build it.",
  `export const INTERACTIVE_ANSWER_PROMPT = ${JSON.stringify(prompt)};`,
  "",
  `export const INTERACTIVE_ANSWER_ROOT = ${JSON.stringify(rootComponent)};`,
  "",
].join("\n");

const schemaContents = [
  "// Generated by scripts/generate-interactive-prompt.mjs — do not edit by hand.",
  "// Kept apart from the prompt so the parser schema loads with the validator,",
  "// not at app startup.",
  `export const INTERACTIVE_ANSWER_SCHEMA = ${JSON.stringify(schema)};`,
  "",
].join("\n");

async function writeIfChanged(target, contents, label) {
  const previous = existsSync(target) ? await readFile(target, "utf8") : "";
  if (previous === contents) return false;
  await writeFile(target, contents, "utf8");
  console.log(`[prompt:ui] wrote ${label}`);
  return true;
}

const wrotePrompt = await writeIfChanged(promptTarget, promptContents, "generated.ts");
const wroteSchema = await writeIfChanged(schemaTarget, schemaContents, "generated-schema.ts");
if (!wrotePrompt && !wroteSchema) {
  console.log("[prompt:ui] up to date");
} else {
  console.log(
    `[prompt:ui] ${prompt.length} prompt chars, ${(JSON.stringify(schema).length / 1024).toFixed(1)} KB schema`,
  );
}
