/** A lucide icon by kebab-case name, or a neutral dot when the name is unknown. */
export function iconByName(name: unknown): LucideIcon {
  const key = typeof name === "string" ? name.trim().toLowerCase() : "";
  return ICONS[key] ?? Circle;
}
